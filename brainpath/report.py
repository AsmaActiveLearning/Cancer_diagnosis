"""Draft neuropathology reports in the WHO CNS5 layered format, grounded in the classifier.

Research drafts only: Virchow and PRISM forbid clinical use, and every report
says so. The layout follows the ICCR dataset for the CNS integrated diagnosis
(WHO CNS5, 2021):

  Integrated diagnosis
  Histopathological classification
  CNS WHO grade
  Molecular information
  Microscopic findings (from the model)
  Comment (confidence, unseen-type flag, evidence, what still needs testing)

Every field comes from a fact the pipeline can show:
  - the tumour type and its probability, from a classifier fit on known types only
    (scored leave-one-out for known slides, so no slide is scored by a model that saw it)
  - an unseen-type flag, when the slide is further from every known type than
    the threshold set on known slides
  - the most typical tiles for the predicted type (level-0 pixel coordinates),
    so a pathologist can check the evidence on the slide
  - age, sex and location from the atlas annotation
  - the WHO CNS5 name, grade and recommended tests for that type, from a lookup
    table (WHO_CNS5 below) that a neuropathologist should check. Because H&E alone
    cannot show IDH, fusion or lineage status, the integrated diagnosis is given
    as NOS (necessary testing not done), with the entity it would become if confirmed.

Nothing the model cannot see on H&E (IDH, 1p/19q, methylation...) is stated as a
finding: those fields say "not assessed" and list the tests to request.

Optionally an open LLM rewrites the microscopic findings and comment as prose
from the same facts (--llm <hugging face model id>, needs a GPU). Its text is
kept only if the integrated diagnosis it writes matches the facts.

Example:
  python -m brainpath.report features/ --out results/reports/
"""

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from brainpath.explore import load
from brainpath.openset import OpenSetDetector
from brainpath.train import l2norm

DISCLAIMER = ("RESEARCH DRAFT - generated by a machine-learning model for research only. "
              "Not a diagnosis; not for patient care.")

