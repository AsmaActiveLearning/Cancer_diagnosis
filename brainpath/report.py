UNKNOWN = {"histology": "Unclassified by the model", "integrated": "Tumour type not recognised by the model",
           "who5": "unknown", "grade": "not assessed",
           "tests": ["full neuropathology work-up", "DNA methylation profiling"]}


def predict_slides(slides, known_keep=0.95, n_typical=5, seed=0):
    """Type, probabilities, unseen flag and typical tiles for every slide, without leakage."""
    emb = l2norm(np.stack([s["features"].mean(0) for s in slides]).astype(np.float64))
    known = np.array([s["role"] != "heldout" for s in slides])
    types = np.array([s["tumour_type"] for s in slides])

    def fit(mask):
        return OpenSetDetector(seed=seed).fit(emb[mask], types[mask])

    # Leave-one-out for known slides; one fit on all known slides for held-out ones.
    known_score = {}
    results = {}
    full = fit(known)
    for i in range(len(slides)):
        if known[i]:
            mask = known.copy()
            mask[i] = False
            if len(set(types[mask])) < 2:
                continue
            det = fit(mask)
        else:
            det = full
        probs = det.clf_.predict_proba(emb[i:i + 1])[0]
        score = det.score(emb[i:i + 1])["prototype"][0]
        results[i] = (det, probs, score)
        if known[i]:
            known_score[i] = score
    threshold = float(np.quantile(list(known_score.values()), known_keep, method="higher"))

    rows = []
    for i, s in enumerate(slides):
        if i not in results:
            continue
        det, probs, score = results[i]
        order = np.argsort(probs)[::-1]
        pred = det.classes_[order[0]]
        # Tiles most similar to the predicted type's centroid: what the call rests on.
        centroid = det.centroids_[list(det.classes_).index(pred)]
        tile_sim = l2norm(s["features"].astype(np.float64)) @ centroid
        top = np.argsort(tile_sim)[::-1][:n_typical]
        coords = s["coords"][top].tolist() if s["coords"] is not None else []
        rows.append({
            "slide_id": s["slide_id"], "true_type": s["tumour_type"], "role": s["role"],
            "pred": pred, "prob": float(probs[order[0]]),
            "top3": [(det.classes_[j], float(probs[j])) for j in order[:3]],
            "unseen_score": float(score), "unseen_threshold": threshold,
            "unknown": bool(score > threshold), "n_tiles": len(s["features"]),
            "typical_tiles": coords, "meta": s["meta"],
        })
    return rows


def facts(row):
    """Everything a report may say about one slide, and nothing else."""
    m = row["meta"]
    entry = UNKNOWN if row["unknown"] else WHO_CNS5.get(row["pred"], {
        "histology": row["pred"], "integrated": f"{row['pred']}, NOS (not in the WHO CNS5 lookup table)",
        "who5": row["pred"], "grade": "not assessed", "tests": []})
    location = m.get("location")
    if isinstance(location, str):
        location = location.strip("[]").replace("'", "") or None
    return {
        "slide_id": row["slide_id"],
        "patient": {"age": m.get("age"), "sex": m.get("sex"), "location": location,
                    "laterality": m.get("laterality") if isinstance(m.get("laterality"), str) else None},
        "model_call": "unknown type" if row["unknown"] else row["pred"],
        "probability": round(row["prob"], 2),
        "alternatives": [{"type": t, "probability": round(p, 2)} for t, p in row["top3"][1:]],
        "unseen_score": round(row["unseen_score"], 3), "unseen_threshold": round(row["unseen_threshold"], 3),
        "integrated_diagnosis": entry["integrated"], "histology": entry["histology"],
        "who_cns5_entity_if_confirmed": entry["who5"], "grade": entry["grade"], "tests_to_request": entry["tests"],
        "tiles_analysed": row["n_tiles"], "typical_tiles_level0_px": row["typical_tiles"],
    }


def confidence_words(p):
    return "high" if p >= 0.8 else "moderate" if p >= 0.5 else "low"


def render(f, microscopy=None, comment=None):
    """The WHO CNS5 layered report as Markdown. microscopy/comment may come from an LLM."""
    pt = f["patient"]
    who = [f"{pt['age']:.0f} years" if isinstance(pt["age"], (int, float)) and not np.isnan(pt["age"]) else None,
           pt["sex"] if isinstance(pt["sex"], str) else None]
    site = ", ".join(x for x in (pt["laterality"], pt["location"]) if x) or "not recorded"
    unknown = f["model_call"] == "unknown type"
    if microscopy is None:
        microscopy = (f"Whole-slide H&E, {f['tiles_analysed']} tissue tiles analysed at 20x. "
                      + ("The morphological profile does not match any tumour type known to the model."
                         if unknown else
                         f"The morphological profile is most similar to {f['model_call']} "
                         f"({confidence_words(f['probability'])} confidence, p = {f['probability']:.2f})."))
    if comment is None:
        alt = "; ".join(f"{a['type']} (p = {a['probability']:.2f})" for a in f["alternatives"])
        comment = ((f"Flagged as a possible unseen tumour type: distance to known types "
                    f"{f['unseen_score']:.3f} exceeds the threshold {f['unseen_threshold']:.3f}. "
                    if unknown else "")
                   + (f"Differential considered by the model: {alt}. " if alt else "")
                   + "Molecular status cannot be determined from H&E and is not assessed. "
                   + "Representative regions for review (level-0 x, y): "
                   + ", ".join(f"({x}, {y})" for x, y in f["typical_tiles_level0_px"]) + ".")
    tests = "\n".join(f"  - {t}" for t in f["tests_to_request"]) or "  - none listed"
    return f"""# Neuropathology report (draft)

> {DISCLAIMER}

**Slide:** {f['slide_id']}
**Patient:** {', '.join(x for x in who if x) or 'not recorded'}
**Site:** {site}

## Integrated diagnosis
{f['integrated_diagnosis']}{'' if unknown else chr(10) + chr(10) + '*WHO CNS5 entity if confirmed:* ' + f['who_cns5_entity_if_confirmed']}

## Histopathological classification
{f['histology']}

## CNS WHO grade
{f['grade']}

## Molecular information
Not assessed. Tests to request:
{tests}

## Microscopic findings
{microscopy}

## Comment
{comment}
"""


def llm_prompt(f):
    return ("You are drafting the 'Microscopic findings' and 'Comment' sections of a research neuropathology "
            "report. Use ONLY the facts in the JSON below. Do not add stains, molecular results, grades, organs "
            "or findings that are not in the facts. If model_call is 'unknown type', say the tumour type is not "
            "recognised and recommend full work-up. Start the comment with the line "
            "'Integrated diagnosis: <integrated_diagnosis value>'. Answer in JSON with keys 'microscopy' and 'comment'.\n\n"
            + json.dumps(f, indent=2, default=str))


def llm_write(f, generate):
    """Ask the LLM for prose; keep it only if it repeats the integrated diagnosis from the facts."""
    text = generate(llm_prompt(f))
    try:
        start, end = text.index("{"), text.rindex("}") + 1
        out = json.loads(text[start:end])
        if f["integrated_diagnosis"].lower() not in out["comment"].lower():
            return None, None, "rejected: integrated diagnosis does not match the facts"
        return out["microscopy"], out["comment"], "accepted"
    except (ValueError, KeyError, TypeError):
        return None, None, "rejected: not valid JSON"


def hf_generator(model_id, max_new_tokens=600):
    from transformers import pipeline
    pipe = pipeline("text-generation", model=model_id, device_map="auto", torch_dtype="auto")

    def generate(prompt):
        out = pipe([{"role": "user", "content": prompt}], max_new_tokens=max_new_tokens, do_sample=False)
        return out[0]["generated_text"][-1]["content"]
    return generate


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("features")
    p.add_argument("--out", default="results/reports")
    p.add_argument("--known-keep", type=float, default=0.95, help="share of known slides the unseen threshold accepts")
    p.add_argument("--llm", default=None, help="optional Hugging Face model id for prose (GPU), e.g. google/medgemma-27b-text-it")
    args = p.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rows = predict_slides(load(args.features), args.known_keep)
    generate = hf_generator(args.llm) if args.llm else None
    summary = []
    for row in rows:
        f = facts(row)
        micro = comment = None
        status = "template only"
        if generate:
            micro, comment, status = llm_write(f, generate)
        (out / f"{Path(row['slide_id']).stem}.md").write_text(render(f, micro, comment))
        (out / f"{Path(row['slide_id']).stem}.json").write_text(json.dumps(f, indent=2, default=str))
        summary.append({"slide_id": row["slide_id"], "true_type": row["true_type"], "role": row["role"],
                        "model_call": f["model_call"], "probability": f["probability"],
                        "correct": row["pred"] == row["true_type"] and not row["unknown"],
                        "unknown_flag": row["unknown"], "llm": status})
    df = pd.DataFrame(summary)
    df.to_csv(out / "reports_summary.csv", index=False)
    known = df[df.role != "heldout"]
    held = df[df.role == "heldout"]
    print(f"{len(df)} reports in {out}")
    print(f"known slides: correct type {known.correct.mean():.0%}, wrongly flagged unknown {known.unknown_flag.mean():.0%}")
    if len(held):
        print(f"held-out slides flagged unknown: {held.unknown_flag.mean():.0%}")


if __name__ == "__main__":
    main()
